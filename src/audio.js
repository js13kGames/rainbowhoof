/**
 * 背景音乐开关
 * @param {boolean} on
 */
export function music(on) {
  if (!on) {
    if (bgm) { try { bgm.stop(); } catch (e) { /* 已停止 */ } bgm = null; }
    return;
  }
  if (bgm) return;
  bgm = zzfxMPlay(MUSIC);
}

/** 首次用户手势时调用：解锁 AudioContext（浏览器策略要求） */
export function unlock() {
  setVolume(AX.volume, AX.muted);
  zzfx(0);                       // 触发 ctx 创建
}

/** 静音切换 */
export function mute(on) {
  setVolume(AX.volume, on);
  if (on) music(false);
}

