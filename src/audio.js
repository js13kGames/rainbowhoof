/** 上一个 play() 的时刻表，用于同名音效的最小间隔节流（防止画线时每帧刷屏） */
const last = {};

/**
 * 播放一个音效。
 * @param {keyof SFX} name 配方名
 * @param {number} [pitchMul=1] 频率倍率（连段升级时把音高抬起来）
 * @param {number} [gap=0] 同名音效最小重触发间隔（秒）
 */
export function play(name, pitchMul, gap) {
  const p = SFX[name];
  if (!p || AX.muted) return null;
  if (gap) {
    const t = performance.now() / 1000;
    if (last[name] !== undefined && t - last[name] < gap) return null;
    last[name] = t;
  }
  // 复制一份再改频率，避免污染配方表
  const q = pitchMul && pitchMul !== 1 ? p.slice() : p;
  if (pitchMul && pitchMul !== 1) q[1] = p[1] * pitchMul;
  return zzfx(...q);
}

